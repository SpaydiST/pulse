  var RU_HIST_BUCKETS = ['<5м', '5-15м', '15-30м', '30-60м', '1-2ч', '2-4ч', '4+ч'];

  function normalizeLangCode(raw) {
    if (!raw || typeof raw !== 'string') return null;
    var base = raw.trim().toLowerCase().split(/[-_]/)[0];
    for (var i = 0; i < LANGS.length; i++) {
      if (LANGS[i].code === base) return base;
    }
    if (base === 'be' || base === 'kk') return 'ru';
    return null;
  }

  function detectInitialLang() {
    try {
      var saved = localStorage.getItem('pulse.lang');
      if (saved) {
        var parsed = JSON.parse(saved);
        var norm = normalizeLangCode(parsed);
        if (norm) return norm;
      }
    } catch (e) { }
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || '';
    return normalizeLangCode(nav) || 'ru';
  }

  var currentLang = detectInitialLang();

  function getLangObj(code) {
    var c = code || currentLang;
    for (var i = 0; i < LANGS.length; i++) {
      if (LANGS[i].code === c) return LANGS[i];
    }
    return LANGS[0];
  }

  function setLang(code, persist) {
    var norm = normalizeLangCode(code) || 'ru';
    currentLang = norm;
    if (persist !== false) {
      try { localStorage.setItem('pulse.lang', JSON.stringify(norm)); } catch (e) { }
    }
    document.documentElement.lang = norm;
    document.title = t('doc.title');
    return norm;
  }

  function applyServerDefault(serverLang) {
    try {
      if (localStorage.getItem('pulse.lang')) return currentLang;
    } catch (e) { }
    var norm = normalizeLangCode(serverLang);
    if (norm) {
      setLang(norm, false);
    }
    return currentLang;
  }

  function t(key) {
    var dict = DICTS[currentLang] || DICTS.ru;
    var val = dict[key];
    if (val === undefined) val = DICTS.en[key];
    if (val === undefined) val = DICTS.ru[key];
    if (val === undefined) return key;
    if (typeof val !== 'string') return val;
    var args = Array.prototype.slice.call(arguments, 1);
    if (!args.length) return val;
    return val.replace(/\{(\d+)\}/g, function (m, idx) {
      var v = args[Number(idx)];
      return v !== undefined && v !== null ? String(v) : m;
    });
  }

  function daysShort() {
    var arr = t('days.short');
    return Array.isArray(arr) ? arr : DICTS.ru['days.short'];
  }

  function daysFull() {
    var arr = t('days.full');
    return Array.isArray(arr) ? arr : DICTS.ru['days.full'];
  }

  function translateWeekday(nameOrIdx, shortForm) {
    var list = shortForm ? daysShort() : daysFull();
    if (typeof nameOrIdx === 'number') {
      return list[((nameOrIdx % 7) + 7) % 7] || String(nameOrIdx);
    }
    if (!nameOrIdx) return '';
    var key = String(nameOrIdx).trim().toLowerCase();
    var idx = WEEKDAY_LOOKUP[key];
    if (idx !== undefined) return list[idx];
    return String(nameOrIdx);
  }

  function translateHistLabels(labels) {
    if (!Array.isArray(labels)) return labels || [];
    var target = t('hist.buckets');
    if (!Array.isArray(target)) return labels;
    return labels.map(function (lbl, i) {
      var idx = RU_HIST_BUCKETS.indexOf(lbl);
      if (idx >= 0 && target[idx]) return target[idx];
      return target[i] || lbl;
    });
  }

  function translateUptime(str) {
    if (!str || currentLang === 'ru') return str || '—';
    return String(str)
      .replace(/\s*д\.\s*/g, t('dur.d', '').trim() + ' ')
      .replace(/\s*ч\.\s*/g, t('dur.h', '').trim() + ' ')
      .replace(/\s*мин\.\s*/g, t('dur.m', '').trim())
      .trim();
  }

  function applyDom(root) {
    var r = root || document;
    var nodes = r.querySelectorAll('[data-i18n]');
    for (var i = 0; i < nodes.length; i++) {
      var el = nodes[i];
      el.textContent = t(el.getAttribute('data-i18n'));
    }
    var phs = r.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < phs.length; j++) {
      var inp = phs[j];
      inp.setAttribute('placeholder', t(inp.getAttribute('data-i18n-placeholder')));
    }
    var tls = r.querySelectorAll('[data-i18n-title]');
    for (var k = 0; k < tls.length; k++) {
      var te = tls[k];
      var tr = t(te.getAttribute('data-i18n-title'));
      te.setAttribute('title', tr);
      if (te.hasAttribute('aria-label')) te.setAttribute('aria-label', tr);
    }
  }

